@pytest.fixture
def shell(monkeypatch):
    """A scripted Applications folder and a recording os.startfile."""

    class Shell:
        entries = [("Calculator", "Microsoft.WindowsCalculator_8wekyb3d8bbwe!App"),
                   ("Python 3.14 (64-bit)", "C:\\Python314\\python.exe"),
                   ("Node.js", "Microsoft.AutoGenerated.{ABC}")]
        scans = 0
        started = []
        refuses = ()

        def scan(self):
            self.scans += 1
            if isinstance(self.entries, OSError):
                raise self.entries
            return list(self.entries)

        def startfile(self, target):
            self.started.append(target)
            if target in self.refuses:
                raise FileNotFoundError(2, "not found")

    fake = Shell()
    fake.started = []
    monkeypatch.setattr(startmenu, "scan_start_menu", fake.scan)
    monkeypatch.setattr(apps.os, "startfile", fake.startfile, raising=False)
    return fake


CALCULATOR = r"shell:AppsFolder\Microsoft.WindowsCalculator_8wekyb3d8bbwe!App"


def test_a_start_menu_name_launches_its_entry(shell):
    WinAppControl().launch("Calculator")
    assert shell.started == [CALCULATOR]


def test_the_name_matches_whatever_its_case(shell):
    WinAppControl().launch("cALCULATOR")
    assert shell.started == [CALCULATOR]


@pytest.mark.parametrize("name, target", [
    ("Python 3.14 (64-bit)", r"shell:AppsFolder\C:\Python314\python.exe"),
    ("Node.js", r"shell:AppsFolder\Microsoft.AutoGenerated.{ABC}"),
])
def test_a_dot_in_a_display_name_is_not_a_file_extension(shell, name, target):
    WinAppControl().launch(name)
    assert shell.started == [target]


@pytest.mark.parametrize("name", [
    "notepad.exe", "NOTEPAD.EXE", "tool.cmd", "services.msc",
    r"C:\Tools\calculator", "tools/calculator", "https://example.com",
    "ms-settings:display",
])
def test_a_file_path_or_url_goes_to_the_shell_without_a_scan(shell, name):
    WinAppControl().launch(name)
    assert shell.started == [name]
    assert shell.scans == 0


@pytest.mark.parametrize("name", ["Calc", "*Calculator*", "Calculator2"])
def test_only_the_whole_name_matches(shell, name):
    WinAppControl().launch(name)
    assert shell.started == [name]


def test_a_name_the_start_menu_does_not_have_goes_to_the_shell(shell):
    WinAppControl().launch("xefm")
    assert shell.started == ["xefm"]


def test_a_known_name_launches_without_scanning_again(shell):
    control = WinAppControl()
    control.launch("Calculator")
    control.launch("Calculator")
    assert shell.scans == 1
    assert shell.started == [CALCULATOR, CALCULATOR]


def test_an_application_installed_since_the_scan_is_found(shell):
    control = WinAppControl()
    control.launch("Calculator")
    shell.entries = shell.entries + [("XeFM", "XeFM_abc!App")]
    control.launch("XeFM")
    assert shell.started[-1] == r"shell:AppsFolder\XeFM_abc!App"


def test_the_store_application_wins_a_shared_name_and_the_user_is_told(shell, caplog):
    shell.entries = [("XeFM", r"C:\Tools\xefm.exe"), ("XeFM", "XeFM_abc!App")]
    with caplog.at_level(logging.WARNING):
        WinAppControl().launch("XeFM")
    assert shell.started == [r"shell:AppsFolder\XeFM_abc!App"]
    assert "2 entries" in caplog.text


def test_an_entry_that_will_not_launch_falls_back_and_is_scanned_again(shell):
    control = WinAppControl()
    control.launch("Calculator")
    shell.refuses = (CALCULATOR,)
    shell.entries = []
    control.launch("Calculator")
    assert shell.started == [CALCULATOR, CALCULATOR, "Calculator"]
    control.launch("Calculator")
    assert shell.scans == 2
    assert shell.started[-1] == "Calculator"


def test_a_start_menu_that_cannot_be_read_leaves_the_shell(shell, caplog):
    shell.entries = OSError("no folder")
    with caplog.at_level(logging.WARNING):
        WinAppControl().launch("Calculator")
    assert shell.started == ["Calculator"]
    assert "no folder" in caplog.text


def test_failure_of_the_shell_itself_still_reaches_the_caller(shell):
    shell.refuses = ("xefm",)
    with pytest.raises(FileNotFoundError):
        WinAppControl().launch("xefm")


@pytest.mark.skipif(sys.platform != "win32", reason="Windows only")
class TestLive:

    def test_the_scan_agrees_with_get_startapps(self):
        """A wrong vtable slot calls a different method; PowerShell is the
        independent answer."""
        command = ("[Console]::OutputEncoding=[Text.Encoding]::UTF8;"
                   "Get-StartApps | ConvertTo-Json -Compress")
        output = subprocess.run(
            ["powershell", "-NoProfile", "-Command", command],
            capture_output=True, encoding="utf-8", check=True,
            creationflags=subprocess.CREATE_NO_WINDOW).stdout
        expected = {(app["Name"], app["AppID"]) for app in json.loads(output)}
        assert set(startmenu.scan_start_menu()) == expected

    def test_entries_are_found_from_a_worker_thread(self):
        from concurrent.futures import ThreadPoolExecutor
        with ThreadPoolExecutor(1) as pool:
            entries = pool.submit(startmenu.scan_start_menu).result()
        assert entries

    @pytest.mark.desktop
    @pytest.mark.parametrize("marker, image", [
        # The three shapes a parsing name comes in.
        ("Microsoft.WindowsCalculator_", "CalculatorApp.exe"),
        ("\\charmap.exe", "charmap.exe"),
        ("Microsoft.Windows.RemoteDesktop", "mstsc.exe"),
    ])
    def test_launch_by_display_name_starts_the_application(
            self, marker, image, monkeypatch, real_home_environ):
        for key, value in real_home_environ.items():
            monkeypatch.setenv(key, value)
        name = next(name for name, parsing in startmenu.scan_start_menu()
                    if marker in parsing)
        try:
            WinAppControl().launch(name)
            deadline = time.monotonic() + 15
            while not _running(image):
                assert time.monotonic() < deadline, f"{name!r}: no {image}"
                time.sleep(0.2)
        finally:
            subprocess.run(["taskkill", "/F", "/IM", image], capture_output=True)

    @pytest.mark.desktop
    def test_launch_from_an_absolute_path_entry_starts_the_application(
            self, monkeypatch, real_home_environ):
        """The fourth shape: python.org's installer puts the path itself in."""
        for key, value in real_home_environ.items():
            monkeypatch.setenv(key, value)
        entries = [(name, parsing) for name, parsing in startmenu.scan_start_menu()
                   if parsing[1:3] == ":\\" and parsing.lower().endswith(".exe")]
        if not entries:
            pytest.skip("no absolute-path entry on this machine")
        name, parsing = entries[0]
        image = parsing.rsplit("\\", 1)[-1]
        before = _pids(image)
        try:
            WinAppControl().launch(name)
            deadline = time.monotonic() + 15
            while not _pids(image) - before:
                assert time.monotonic() < deadline, f"{name!r}: no new {image}"
                time.sleep(0.2)
        finally:
            for pid in _pids(image) - before:
                subprocess.run(["taskkill", "/F", "/PID", str(pid)],
                               capture_output=True)


def _pids(image):
    output = subprocess.run(
        ["tasklist", "/FI", f"IMAGENAME eq {image}", "/FO", "CSV", "/NH"],
        capture_output=True, text=True).stdout
    return {int(line.split('","')[1]) for line in output.splitlines()
            if line.lower().startswith(f'"{image.lower()}"')}


def _running(image):
    return bool(_pids(image))
