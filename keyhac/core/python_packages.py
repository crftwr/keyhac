"""Extra Python libraries declared in ``~/.keyhac/requirements.txt`` (#272).

``config.py`` and ``extensions/`` can import only what the Keyhac build ships.
The macOS app (DMG, Homebrew cask) and the Windows app (zip, Store) are sealed
bundles, so nothing can be added inside them, and ``pip install --target``
into ``extensions/`` is the wrong place: that directory is re-imported on every
reload, which is right for your own modules and wrong for a library with state
or a C extension.

This module is the route that works for every install, and it is
declarative::

    ~/.keyhac/requirements.txt         <- the user writes this, next to config.py
    ~/.keyhac/site-packages/3.14/      <- generated by `sync`, never edited by hand
        .stamp                         <- what the directory was synced from

**Sync** runs pip -- on the interpreter Keyhac runs on, so the ABI always
matches -- with ``--target`` into a staging directory, then swaps that in
whole. A line deleted from the file therefore removes its package, which
``pip --target`` would not do on its own. The packages Keyhac itself runs on
win: they are passed to pip as constraints pinned to their exact versions,
then pruned from the result, so the directory never holds a second PyObjC. A
requirement that conflicts with them fails the sync, and the failure names the
conflict.

**Sync is the only thing in Keyhac that reaches the network**, and only when
the user starts it (the tray menu, or ``keyhac deps sync``).

**Load** appends the directory to ``sys.path`` with ``site.addsitedir`` before
``config.py`` runs. It is separate from ``extensions/`` and is not purged on a
config reload.

**The startup check** is offline: it compares ``.stamp`` and nothing else, and
says when a sync is needed. It never syncs by itself.

The same design as XeFM's ``xefm/python_packages.py`` (crftwr/xefm#664);
keep the two in step.
"""

import hashlib
import importlib
import importlib.metadata
import importlib.util
import json
import os
import platform
import re
import shutil
import site
import subprocess
import sys
import tempfile
import urllib.request
from dataclasses import dataclass, field
from pathlib import Path
from typing import Callable

from keyhac.core import log, paths

logger = log.getLogger("PyPackages")

REQUIREMENTS = "requirements.txt"
STAMP = ".stamp"
PYPI_PIP_JSON = "https://pypi.org/pypi/pip/json"


# --- where things live ----------------------------------------------------------

def python_version() -> str:
    """``3.14`` -- the directory a sync writes to is per minor version, because
    a C extension built for one does not load in another."""
    return f"{sys.version_info.major}.{sys.version_info.minor}"


def platform_tag() -> str:
    """Interpreter, OS and machine: what decides whether a compiled package in
    the directory can load here at all. ``~/.keyhac`` travels with dotfiles,
    and one config runs on both OSes, so the directory may have been synced on
    another machine."""
    return "-".join(filter(None, (sys.implementation.cache_tag, sys.platform,
                                  platform.machine().lower(),
                                  getattr(sys, "abiflags", ""))))


@dataclass
class Layout:
    """Where the files live, under one data directory (``~/.keyhac``, the
    ``--config`` directory, or the portable bundle directory)."""

    home: Path = field(default_factory=lambda: Path(paths.default_data_dir()))
    version: str = field(default_factory=python_version)

    def __post_init__(self):
        self.home = Path(self.home)

    @property
    def requirements(self) -> Path:
        return self.home / REQUIREMENTS

    @property
    def root(self) -> Path:
        return self.home / "site-packages"

    @property
    def target(self) -> Path:
        return self.root / self.version

    @property
    def staging(self) -> Path:
        """Where a sync builds the next directory. Left in place when the swap
        cannot happen yet (Windows, with one of the old packages loaded) and
        swapped in at the next start instead."""
        return self.root / f".{self.version}.new"

    @property
    def retired(self) -> Path:
        return self.root / f".{self.version}.old"

    @property
    def pip_cache(self) -> Path:
        """A downloaded pip wheel, for an interpreter that has neither pip nor
        ensurepip (the Windows app's embeddable CPython)."""
        return self.root / ".pip"


# --- what was asked for, and what Keyhac already has ----------------------------

def read_requirements(layout: Layout) -> str:
    try:
        return layout.requirements.read_text(encoding="utf-8")
    except FileNotFoundError:
        return ""


def declares_anything(text: str) -> bool:
    """Whether a requirements file asks for anything -- blank lines and
    comments alone do not."""
    return any(line.split("#", 1)[0].strip() for line in text.splitlines())


def normalize(name: str) -> str:
    """PEP 503: ``PyObjC-Core``, ``pyobjc_core`` and ``pyobjc.core`` name one
    project."""
    return re.sub(r"[-_.]+", "-", name).lower()


def host_distributions(layout: Layout) -> dict[str, str]:
    """``{normalized name: version}`` for every distribution Keyhac can import
    without the synced directory -- what the bundle ships, or what the venv it
    was installed into holds. The first one on the path wins, as it would for
    an import."""
    own = str(layout.root.resolve())
    found: dict[str, str] = {}
    for dist in importlib.metadata.distributions():
        name, version = dist.metadata["Name"], dist.version
        if not name or not version:
            continue
        try:
            location = str(Path(dist.locate_file("")).resolve())
        except (OSError, TypeError):
            location = ""
        if location == own or location.startswith(own + os.sep):
            continue
        found.setdefault(normalize(name), version)
    return found


def _sha256(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def _host_digest(host: dict[str, str]) -> str:
    return _sha256("\n".join(f"{n}=={v}" for n, v in sorted(host.items())))


def make_stamp(requirements: str, host: dict[str, str]) -> dict:
    return {"requirements": _sha256(requirements), "host": _host_digest(host),
            "python": python_version(), "platform": platform_tag()}


def read_stamp(directory: Path) -> dict | None:
    try:
        return json.loads((directory / STAMP).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None


# --- the startup check ----------------------------------------------------------

#: Nothing declared and nothing synced: the feature is not in use.
UNUSED = "unused"
#: The directory matches the file, this Python and Keyhac's own packages.
IN_SYNC = "in-sync"
#: A sync is due; the directory (if any) is still loaded.
NEEDS_SYNC = "needs-sync"
#: The directory was synced for another platform and is not loaded.
FOREIGN = "foreign"



def _how_to_sync() -> str:
    """The tray menu always; the ``keyhac deps`` command only where it
    exists. The app bundles are desktop apps with no ``keyhac`` on PATH, and
    a message naming one sends the user looking for something that is not
    there."""
    if in_app_bundle():
        return "Choose Sync Python Packages in the tray menu."
    return ("Choose Sync Python Packages in the tray menu, or run "
            "`keyhac deps sync`.")


@dataclass
class Status:
    state: str
    reason: str = ""
    loaded: bool = False

    @property
    def message(self) -> str:
        if self.state == NEEDS_SYNC:
            return f"Python packages need a sync: {self.reason}. {_how_to_sync()}"
        if self.state == FOREIGN:
            return f"Python packages not loaded: {self.reason}. {_how_to_sync()}"
        return ""


def check(layout: Layout, host: dict[str, str] | None = None) -> Status:
    """Compare the stamp with the file, this Python and Keyhac's own packages.
    Offline and cheap; says what is out of date, and never fixes it."""
    text = read_requirements(layout)
    stamp = read_stamp(layout.target) if layout.target.is_dir() else None
    if stamp is None:
        if layout.target.is_dir():
            return Status(NEEDS_SYNC, f"{layout.target} has no {STAMP}", loaded=True)
        if not declares_anything(text):
            return Status(UNUSED)
        others = sorted(p.name for p in layout.root.glob("[0-9]*.[0-9]*") if p.is_dir())
        if others:
            return Status(NEEDS_SYNC, f"{layout.requirements} was synced for Python "
                          f"{', '.join(others)}, and Keyhac now runs on {layout.version}")
        return Status(NEEDS_SYNC, f"{layout.requirements} has not been synced yet")
    if stamp.get("platform") != platform_tag():
        return Status(FOREIGN, f"{layout.target} was synced for "
                      f"{stamp.get('platform')}, not {platform_tag()}")
    if stamp.get("requirements") != _sha256(text):
        return Status(NEEDS_SYNC, f"{layout.requirements} changed since the last sync",
                      loaded=True)
    if host is None:
        host = host_distributions(layout)
    if stamp.get("host") != _host_digest(host):
        return Status(NEEDS_SYNC, "Keyhac's own packages changed since the last sync "
                      "(an upgrade, or another Keyhac install sharing the directory)",
                      loaded=True)
    return Status(IN_SYNC, loaded=True)


# --- loading --------------------------------------------------------------------

def _swap_in(layout: Layout) -> bool:
    """Replace the target directory with the staged one. False if the old one
    cannot be moved yet -- on Windows, a loaded ``.pyd`` holds its directory --
    in which case nothing has changed and the staged directory waits."""
    shutil.rmtree(layout.retired, ignore_errors=True)
    had_target = layout.target.exists()
    try:
        if had_target:
            os.replace(layout.target, layout.retired)
    except OSError as e:
        logger.info(f"Could not replace {layout.target} while it is in use: {e}")
        return False
    try:
        os.replace(layout.staging, layout.target)
    except OSError as e:
        logger.error(f"Could not move {layout.staging} into place: {e}")
        if had_target:
            os.replace(layout.retired, layout.target)
        return False
    shutil.rmtree(layout.retired, ignore_errors=True)
    return True


def activate(layout: Layout | None = None) -> Status:
    """Before ``config.py`` runs: finish a sync that was waiting for a restart,
    append the directory to ``sys.path`` unless it was synced for another
    platform, and say whether a sync is due. Called on every config load; a
    directory already on the path is left alone."""
    layout = layout or Layout()
    if layout.staging.is_dir():
        if read_stamp(layout.staging) is None:
            # An interrupted sync: never swap in a half-built directory.
            shutil.rmtree(layout.staging, ignore_errors=True)
        elif str(layout.target.resolve()) not in sys.path:
            _swap_in(layout)
    try:
        status = check(layout)
    except Exception as e:
        logger.error(f"Could not check {layout.target}: {e}")
        return Status(UNUSED)
    if status.loaded:
        _add_to_path(layout.target)
    return status


def _add_to_path(directory: Path) -> None:
    resolved = str(directory.resolve())
    if resolved not in sys.path:
        # Appended, like extensions/: Keyhac's own packages stay first.
        # addsitedir also runs the directory's .pth files, which some packages
        # (pywin32 among them) need in order to import at all. Importing site
        # is safe where the launcher disabled it (Windows: site_import = 0):
        # site.main() then does not run, and addsitedir needs none of it.
        site.addsitedir(resolved)
    importlib.invalidate_caches()


# --- the interpreter, and its pip ----------------------------------------------

class SyncError(Exception):
    """A sync that did not complete. The target directory is untouched."""


Runner = Callable[..., "subprocess.CompletedProcess"]
Opener = Callable[[str], bytes]

#: Windows gives a console program its own window whenever the parent has
#: none, which is every launch from the GUI app; pip's output is piped anyway.
_NO_WINDOW = ({"creationflags": subprocess.CREATE_NO_WINDOW}
              if sys.platform == "win32" else {})


def in_app_bundle() -> bool:
    """Whether Keyhac runs from the macOS or Windows app rather than under a
    real ``python`` (a pip, pipx or uv install, or a source checkout). In the
    bundles ``sys.executable`` is the launcher, never named ``python*``."""
    name = os.path.basename(sys.executable or "").lower()
    return not name.startswith("python")


def keyhac_python() -> str:
    r"""The interpreter pip runs on: the one Keyhac itself runs on.

    ``sys.executable`` whenever Keyhac runs under a real ``python`` (a pip,
    pipx or uv install, or a source checkout). In the bundles it is the
    launcher instead, which runs Keyhac whatever arguments it is given:

    - macOS: ``Keyhac.app/Contents/MacOS/Keyhac``. The launcher sets the
      framework as the interpreter's home, so ``sys.base_prefix`` is
      ``Contents/Frameworks/Python.framework/Versions/Current``, whose
      ``bin/python3`` build.sh makes runnable on its own (the MCP bridge
      runs it too).
    - Windows: ``<root>\Keyhac.exe``, with the embeddable CPython's
      ``python.exe`` under ``<root>\runtime``.
    """
    executable = sys.executable or ""
    if not in_app_bundle():
        return executable
    if sys.platform == "darwin":
        return os.path.join(sys.base_prefix, "bin", "python3")
    if sys.platform == "win32":
        root = paths.bundle_dir() or os.path.dirname(executable)
        return os.path.join(root, "runtime", "python.exe")
    return executable


def _pip_env() -> dict:
    env = dict(os.environ)
    # The user's own pip settings must not redirect this install.
    for name in ("PIP_TARGET", "PIP_PREFIX", "PIP_USER", "PIP_REQUIRE_VIRTUALENV"):
        env.pop(name, None)
    # Nothing may write bytecode into the signed macOS bundle: a .pyc there
    # breaks the seal of the installed copy. pip still compiles what it
    # installs into the target, which is outside the bundle.
    env["PYTHONDONTWRITEBYTECODE"] = "1"
    return env


def _bundled_pip_wheel() -> Path | None:
    """The pip wheel ensurepip carries. Run straight from the wheel, which pip
    supports, it needs no install anywhere."""
    spec = importlib.util.find_spec("ensurepip")
    if spec is None or not spec.origin:
        return None
    wheels = sorted((Path(spec.origin).parent / "_bundled").glob("pip-*.whl"))
    return wheels[-1] if wheels else None


def _download_pip_wheel(layout: Layout, opener: Opener) -> Path:
    """The latest pip wheel from PyPI, checked against the digest PyPI lists
    for it, kept under ``site-packages/.pip`` so this happens once."""
    cached = sorted(layout.pip_cache.glob("pip-*.whl"))
    if cached:
        return cached[-1]
    try:
        info = json.loads(opener(PYPI_PIP_JSON))
        wheel = next(u for u in info["urls"]
                     if u.get("packagetype") == "bdist_wheel"
                     and u["filename"].endswith("-py3-none-any.whl"))
        payload = opener(wheel["url"])
    except (OSError, ValueError, KeyError, StopIteration) as e:
        raise SyncError(f"no pip here, and it could not be downloaded: {e}") from None
    if hashlib.sha256(payload).hexdigest() != wheel["digests"]["sha256"]:
        raise SyncError(f"the downloaded {wheel['filename']} does not match "
                        "the digest PyPI lists for it")
    layout.pip_cache.mkdir(parents=True, exist_ok=True)
    path = layout.pip_cache / wheel["filename"]
    path.write_bytes(payload)
    return path


def _urlopen(url: str) -> bytes:
    with urllib.request.urlopen(url, timeout=60) as response:
        return response.read()


def pip_command(python: str, layout: Layout, run: Runner = subprocess.run,
                opener: Opener = _urlopen) -> list[str]:
    """How to run pip on ``python``, best first: its own pip (a pip or pipx
    install), else the wheel ensurepip carries (the macOS app, a uv venv),
    else one downloaded from PyPI (the Windows app's embeddable CPython has
    neither)."""
    probe = run([python, "-m", "pip", "--version"], capture_output=True,
                stdin=subprocess.DEVNULL, env=_pip_env(), **_NO_WINDOW)
    if probe.returncode == 0:
        return [python, "-m", "pip"]
    wheel = _bundled_pip_wheel() or _download_pip_wheel(layout, opener)
    return [python, os.path.join(str(wheel), "pip")]


# --- sync -----------------------------------------------------------------------

@dataclass
class SyncResult:
    installed: list[str]          # "name version", what the directory now holds
    pruned: list[str]             # names Keyhac already provides, left out
    pending_restart: bool = False # staged; swapped in at the next start


def _prune(directory: Path, host: dict[str, str]) -> list[str]:
    """Remove from ``directory`` every distribution Keyhac already has -- pip
    put them there because ``--target`` resolves as if nothing were
    installed. The constraints made them the very same versions, so the
    host's copy is what would be imported anyway."""
    pruned = []
    root = directory.resolve()
    for dist in list(importlib.metadata.distributions(path=[str(directory)])):
        name = dist.metadata["Name"]
        if not name or normalize(name) not in host:
            continue
        dirs = set()
        for entry in dist.files or ():
            path = Path(dist.locate_file(entry)).resolve()
            # RECORD may name scripts outside the site directory ("../../bin");
            # never delete anything that is not inside it.
            if root not in path.parents:
                continue
            try:
                path.unlink()
            except FileNotFoundError:
                pass
            dirs.add(path.parent)
        info_dir = getattr(dist, "_path", None)
        if info_dir is not None:
            shutil.rmtree(info_dir, ignore_errors=True)
        for d in sorted(dirs, key=lambda p: len(p.parts), reverse=True):
            while d != root and root in d.parents:
                try:
                    d.rmdir()
                except OSError:
                    break
                d = d.parent
        pruned.append(name)
    return sorted(pruned, key=str.lower)


def _conflict_lines(output: list[str]) -> list[str]:
    """pip's own account of a requirement that clashes with a pinned host
    package -- the indented lines under "The conflict is caused by:" -- or
    nothing when no pinned host package is among them."""
    lines, inside = [], False
    for line in output:
        if line.strip().startswith("The conflict is caused by"):
            inside, lines = True, []
        elif inside and line.startswith((" ", "\t")) and line.strip():
            lines.append(line.strip())
        else:
            inside = False
    return lines if any("(constraint)" in line for line in lines) else []


def sync(layout: Layout | None = None, python: str | None = None,
         log: Callable[[str], None] = lambda line: None,
         run: Runner = subprocess.run, popen=subprocess.Popen,
         opener: Opener = _urlopen) -> SyncResult:
    """Bring the directory to match ``requirements.txt``. pip's output goes
    to ``log`` a line at a time. Raises :class:`SyncError` and leaves the
    current directory as it was when anything fails. Reaches the network."""
    layout = layout or Layout()
    python = python or keyhac_python()
    text = read_requirements(layout)
    declared = declares_anything(text)
    if not declared and not layout.target.exists():
        return SyncResult([], [])
    host = host_distributions(layout)
    shutil.rmtree(layout.staging, ignore_errors=True)
    layout.staging.mkdir(parents=True)
    try:
        if declared:
            _pip_install(layout, python, host, log, run, popen, opener)
            pruned = _prune(layout.staging, host)
        else:
            pruned = []
        (layout.staging / STAMP).write_text(
            json.dumps(make_stamp(text, host), indent=2), encoding="utf-8")
    except BaseException:
        shutil.rmtree(layout.staging, ignore_errors=True)
        raise
    installed = sorted(
        (f"{d.metadata['Name']} {d.version}"
         for d in importlib.metadata.distributions(path=[str(layout.staging)])
         if d.metadata["Name"]), key=str.lower)
    # Swapped in even when nothing is declared: an empty directory replaces
    # the old one the same way, waiting for a restart if it has to.
    swapped = _swap_in(layout)
    if swapped and not declared:
        shutil.rmtree(layout.target, ignore_errors=True)
        try:
            layout.root.rmdir()
        except OSError:
            pass  # not empty: the downloaded pip, or another Python's directory
    elif swapped:
        _add_to_path(layout.target)
    return SyncResult(installed, pruned, pending_restart=not swapped)


def _pip_install(layout, python, host, log, run, popen, opener) -> None:
    pip = pip_command(python, layout, run=run, opener=opener)
    with tempfile.TemporaryDirectory(prefix="keyhac-deps-") as tmp:
        constraints = Path(tmp) / "host-constraints.txt"
        constraints.write_text("".join(f"{n}=={v}\n" for n, v in sorted(host.items())),
                               encoding="utf-8")
        argv = pip + ["install", "--target", str(layout.staging),
                      "--no-input", "--disable-pip-version-check",
                      "-r", str(layout.requirements), "-c", str(constraints)]
        logger.info(f"Running: {' '.join(argv)}")
        output: list[str] = []
        try:
            # cwd is the data directory, so a relative path in
            # requirements.txt means what it says relative to the file.
            proc = popen(argv, cwd=str(layout.home), env=_pip_env(),
                         stdin=subprocess.DEVNULL, stdout=subprocess.PIPE,
                         stderr=subprocess.STDOUT, text=True, errors="replace",
                         **_NO_WINDOW)
        except OSError as e:
            raise SyncError(f"could not run pip: {e}") from None
        for line in proc.stdout:
            line = line.rstrip("\n")
            output.append(line)
            log(line)
        proc.stdout.close()
        code = proc.wait()
    if code != 0:
        conflicts = _conflict_lines(output)
        if conflicts:
            raise SyncError("a requirement conflicts with a package Keyhac itself "
                            "runs on, whose version wins: " + "; ".join(conflicts))
        raise SyncError(f"pip exited with code {code}")
